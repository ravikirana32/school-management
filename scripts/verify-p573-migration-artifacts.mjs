import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = process.cwd();
const migrationRoot = path.join(root, 'backend/api/prisma/migrations');
const checks = [];
const add = (name, pass, detail = '') => checks.push({ name, pass: Boolean(pass), detail });

const schemaPath = path.join(root, 'backend/api/prisma/schema.prisma');
const lockPath = path.join(migrationRoot, 'migration_lock.toml');
const migrationDirs = fs.existsSync(migrationRoot)
  ? fs.readdirSync(migrationRoot, { withFileTypes: true }).filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort()
  : [];
const missingSql = [];
const emptySql = [];
const invalidNames = [];
const timestampGroups = new Map();
for (const name of migrationDirs) {
  if (!/^\d{14}_[a-z0-9_]+$/.test(name)) invalidNames.push(name);
  const prefix = name.slice(0, 14);
  timestampGroups.set(prefix, [...(timestampGroups.get(prefix) ?? []), name]);
  const sqlPath = path.join(migrationRoot, name, 'migration.sql');
  if (!fs.existsSync(sqlPath)) missingSql.push(name);
  else if (fs.statSync(sqlPath).size === 0) emptySql.push(name);
}
const duplicateTimestamps = [...timestampGroups.entries()].filter(([, names]) => names.length > 1);
const duplicateFullNames = migrationDirs.length !== new Set(migrationDirs).size;

add('Prisma schema file exists', fs.existsSync(schemaPath));
add('PostgreSQL migration lock declares provider', fs.existsSync(lockPath) && /provider\s*=\s*"postgresql"/.test(fs.readFileSync(lockPath, 'utf8')));
add('Migration directory naming convention', invalidNames.length === 0, invalidNames.length ? invalidNames.join(', ') : `${migrationDirs.length} directories conform`);
add('Every migration directory has migration.sql', missingSql.length === 0, missingSql.length ? missingSql.join(', ') : `${migrationDirs.length} files present`);
add('No empty migration.sql files', emptySql.length === 0, emptySql.length ? emptySql.join(', ') : 'all SQL files are non-empty');
add('Migration directory names are unique', !duplicateFullNames);

const packageJson = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
add('Pinned package manager is pnpm 9.15.0', packageJson.packageManager === 'pnpm@9.15.0', packageJson.packageManager ?? 'missing');
add('Real pnpm lockfile exists', fs.existsSync(path.join(root, 'pnpm-lock.yaml')), 'Required for frozen install; must be generated by pnpm, not hand-authored');

const pass = checks.filter((check) => check.pass).length;
const fail = checks.length - pass;
console.log(JSON.stringify({ phase: 'P573', migrationDirectoryCount: migrationDirs.length, migrationSqlCount: migrationDirs.length - missingSql.length, duplicateTimestampPrefixCount: duplicateTimestamps.length, duplicateTimestampPrefixes: duplicateTimestamps, checks, pass, fail, result: fail === 0 ? 'PASS' : 'BLOCKED' }, null, 2));
if (fail > 0) process.exitCode = 1;

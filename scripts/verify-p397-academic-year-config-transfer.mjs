import fs from 'node:fs';
import vm from 'node:vm';
const transferPath = 'apps/school-admin/src/school-config-transfer.ts';
const workspacePath = 'apps/school-admin/src/SchoolConfigurationWorkspace.tsx';
const transfer = fs.readFileSync(transferPath, 'utf8');
const workspace = fs.readFileSync(workspacePath, 'utf8');
const checks = [];
function check(label, condition) { checks.push({ label, pass: Boolean(condition) }); }
check('academic scope is part of transfer type', /ConfigTransferTab\s*=.*"academic"/.test(transfer));
check('academic-year array is required and bounded', /academicYears[\s\S]*1–20 academic years/.test(transfer));
check('year name validation exists', /Academic year \$\{yi \+ 1\}: name is required/.test(transfer));
check('year code validation exists', /Academic year \$\{yi \+ 1\}: code is required/.test(transfer));
check('duplicate year code validation exists', /Duplicate academic year code/.test(transfer));
check('year date range validation exists', /end must not precede start/.test(transfer));
check('term array shape validation exists', /terms must be an array/.test(transfer));
check('term name/code validation exists', /term \$\{ti \+ 1\}: name is required/.test(transfer) && /term \$\{ti \+ 1\}: code is required/.test(transfer));
check('duplicate term code validation exists', /duplicate term code/.test(transfer));
check('term sequence validation exists', /sequence must be 1–20/.test(transfer));
check('duplicate term sequence validation exists', /duplicate term sequence/.test(transfer));
check('term type whitelist exists', /unsupported termType/.test(transfer));
check('term date bounds within year enforced', /dates must be valid and within the academic year/.test(transfer));
check('workspace exports academic year terms from API', /read\(`\/academic-years\//.test(workspace) && /terms\.map\(\(term/.test(workspace));
check('preview rejects existing school year codes', /existingCodes[\s\S]*already exists in this school/.test(workspace));
check('academic apply creates years and nested terms', /write\("\/academic-years", "POST"[\s\S]*write\(`\/academic-years\//.test(workspace));
check('academic apply permission gate is specific', /academics\.manage/.test(workspace));
check('academic import is atomic and reports rollback on failure', /single server-side database transaction/.test(workspace) && /server transaction was rolled back/.test(workspace));
check('imported year defaults not-current to avoid source state mutation', /makeCurrent: raw\.makeCurrent \?\? false/.test(fs.readFileSync('backend/api/src/modules/schools/school-config.routes.ts','utf8')));
check('existing year records are not updated or deleted', /Existing records will not be modified/.test(workspace));
for (const item of checks) console.log(`${item.pass?'PASS':'FAIL'} ${item.label}`);
console.log(`RESULT ${checks.filter(x=>x.pass).length}/${checks.length}`);
if (checks.some(x=>!x.pass)) process.exitCode=1;

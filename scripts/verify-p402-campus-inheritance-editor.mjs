import fs from 'node:fs';
const source = fs.readFileSync('apps/school-admin/src/campus-inheritance-editor.ts', 'utf8');
const checks = [];
const check = (name, pass) => checks.push({ name, pass });
check('draft factory exported', /export function createCampusInheritanceDraft/.test(source));
check('draft factory uses supported scope list', source.includes('inheritedScopes: [...CAMPUS_INHERITABLE_SCOPES]'));
check('draft validates before return', /const validation = validateCampusInheritanceDocument\(draft\)[\s\S]*if \(!validation\.valid\) throw/.test(source));
check('inheritance toggle exported', /export function setCampusScopeInheritance/.test(source));
check('scope toggle rejects unknown scope', /setCampusScopeInheritance[\s\S]*if \(!CAMPUS_INHERITABLE_SCOPES\.includes\(scope\)\)/.test(source));
check('inheritance toggle retains overrides', /overrides: cloneValue\(document\.overrides\)/.test(source));
check('override set exported', /export function setCampusScopeOverride/.test(source));
check('override setter clones existing overrides', /const overrides = cloneValue\(document\.overrides\)/.test(source));
check('override removal exported', /export function removeCampusScopeOverride/.test(source));
check('override removal uses delete', /delete overrides\[scope\]/.test(source));
check('nested path update exported', /export function setCampusOverridePath/.test(source));
check('path validation blocks unsafe keys', /segments\.some\(segment => !segment \|\| unsafeSegments\.has\(segment\)/.test(source));
check('path update supports object-only traversal', /if \(!isPlain\(cursor\[segment\]\)\) cursor\[segment\] = \{\}/.test(source));
check('summary export exposes scope state', /export function summarizeCampusOverrideScopes/.test(source));
check('summary returns inherited and override presence', /inherited: document\.inheritedScopes\.includes\(scope\), hasOverride: Object\.prototype\.hasOwnProperty\.call\(document\.overrides, scope\)/.test(source));
check('prototype-danger keys are excluded from cloning', /unsafeSegments = new Set\(\["__proto__", "prototype", "constructor"\]\)/.test(source));
for (const c of checks) console.log(`${c.pass ? 'PASS' : 'FAIL'} ${c.name}`);
console.log(`RESULT ${checks.filter(c => c.pass).length}/${checks.length}`);
if (checks.some(c => !c.pass)) process.exitCode = 1;

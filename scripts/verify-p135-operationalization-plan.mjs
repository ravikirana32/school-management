import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const routes=read('backend/api/src/modules/parents/parent.routes.ts');
const ui=read('apps/school-admin/src/FinanceWorkspace.tsx');
const gaps=read('MASTER-OPEN-GAPS-REGISTER.md');
const checks=[];const check=(name,fn)=>{fn();checks.push(name);};
check('dependency plan endpoint is authenticated and permission scoped',()=>assert.match(routes,/operationalization-plan",authenticate[\s\S]*?scope\(req,res,"accounting\.reconcile"\)/));
check('requested batch selection is bounded',()=>assert.match(routes,/requested\.length>200/));
check('planner loads only tenant-scoped posted batches',()=>assert.match(routes,/organizationId:s\.organizationId,schoolId:s\.schoolId,status:"POSTED"/));
check('planner reads tenant-scoped persisted allocation edges',()=>assert.match(routes,/accountingHistoricalAllocation\.findMany\(\{where:\{organizationId:s\.organizationId,schoolId:s\.schoolId\}/));
check('prerequisites are expanded transitively',()=>assert.match(routes,/includePrerequisites/));
check('dependency order is topologically calculated',()=>assert.match(routes,/indegree\.set\(source[\s\S]*?while\(ready\.length\)/));
check('dependency cycles are explicitly returned',()=>assert.match(routes,/cycleIds=\[\.\.\.selected\]\.filter/));
check('plan reports readiness and blocked prerequisites',()=>assert.match(routes,/blockedBy:pending/));
check('plan is read-only and does not invoke operationalization',()=>assert.match(routes,/plan is advisory and does not mutate batches or post journals/));
check('School Admin loads and displays dependency plan',()=>assert.match(ui,/loadOperationalizationPlan[\s\S]*?operationalizationPlan\.plan/));
check('School Admin reports cycle blockers',()=>assert.match(ui,/cycleBatchIds/));
check('split allocation limitation remains explicitly documented',()=>assert.match(gaps,/P135-G002[\s\S]*?OPEN/));
check('P134 dependency gap is not falsely closed',()=>assert.match(gaps,/P134-G002[\s\S]*?PARTIALLY_IMPLEMENTED/));
console.log(`P135 static verification: ${checks.length}/${checks.length} PASS`);
for(const name of checks)console.log(`PASS ${name}`);

import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const exists=(p)=>fs.existsSync(path.join(root,p));
const checks=[];
const test=(name,condition)=>checks.push({name,pass:Boolean(condition)});
const schema=read('backend/api/prisma/schema.prisma');
const migrationsDir=path.join(root,'backend/api/prisma/migrations');
const migrations=fs.readdirSync(migrationsDir,{withFileTypes:true}).filter(x=>x.isDirectory()).map(x=>x.name);
const missingSql=migrations.filter(m=>!fs.existsSync(path.join(migrationsDir,m,'migration.sql')));
const gap=read('MASTER-OPEN-GAPS-REGISTER.md');
const progress=read('C2-10-PROGRESS.md');
const roadmap=read('C2-10-ROADMAP.md');
const requiredModels=['LibraryCopy','LibraryReservation','TransportTrip','TransportIncident','HostelAttendanceSession','HostelLeaveRequest','HostelBedTransfer','HostelWaitlistEntry','HostelFeePlan','HostelDepositAccount','HostelSafeguardingCase'];
for(const model of requiredModels)test(`Integrated schema retains ${model}`,new RegExp(`model ${model} \\{`).test(schema));
test('All migration folders contain migration.sql',missingSql.length===0);
test('Migration history contains expected transport, library and hostel phases',migrations.some(x=>x.includes('p554'))&&migrations.some(x=>x.includes('p565'))&&migrations.some(x=>x.includes('p570')));
test('P538-P570 progress history retained',progress.includes('P538')&&progress.includes('P570 completion'));
test('C2-10 roadmap retained',roadmap.includes('P571')&&roadmap.includes('P538'));
test('Master register retains carried-forward P00 gaps',gap.includes('P00-G001')&&gap.includes('P00-G020'));
test('Master register retains P569 gaps',gap.includes('P569-G001')||gap.includes('P569'));
test('Master register retains P570 gaps',gap.includes('P570-G001')||gap.includes('P570'));
for(const f of ['backend/api/src/modules/hostel/hostel.routes.ts','backend/api/src/modules/parents/parent.routes.ts','apps/school-admin/src/HostelWorkspace.tsx','apps/parent-mobile/src/hostel/HostelLeaveScreen.tsx'])test(`P570 hostel integration file ${f}`,exists(f));
for(const f of ['backend/api/src/modules/transport','backend/api/src/modules/library'])test(`Cross-module source directory ${f}`,exists(f));
const apps=['super-admin','organization-admin','school-admin','public-portal','teacher-mobile','parent-mobile','student-mobile','staff-mobile','driver-mobile'];
for(const app of apps)test(`Application package retained: ${app}`,exists(`apps/${app}/package.json`));
test('P570 focused verifier retained',exists('scripts/verify-p570-hostel-finance-duty-maintenance-safeguarding.mjs'));
test('Static verifier runner retained',exists('scripts/run-static-verifiers.mjs'));
test('No package lock is present (environment blocker documented)',!exists('pnpm-lock.yaml'));
const failed=checks.filter(x=>!x.pass);
console.log(`P571 integration assertions: ${checks.length-failed.length}/${checks.length} PASS`);
console.log(`Migration folders: ${migrations.length}; missing migration.sql: ${missingSql.length}`);
for(const x of failed)console.log(`FAIL ${x.name}`);
if(failed.length)process.exit(1);

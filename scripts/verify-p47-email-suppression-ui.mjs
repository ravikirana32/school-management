import { readFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
const root = process.cwd();
const read = (path) => readFileSync(resolve(root, path), "utf8");
const checks = [];
function check(name, condition) { checks.push({ name, pass: Boolean(condition) }); }
const component = read("apps/school-admin/src/NotificationSuppressionWorkspace.tsx");
const main = read("apps/school-admin/src/main.tsx");
const routes = read("backend/api/src/modules/notifications/suppression.routes.ts");
const session = read("apps/school-admin/src/SchoolAdminSession.tsx");
const pdf = read("backend/api/src/modules/report-cards/report-card-pdf.ts");
const register = read("MASTER-OPEN-GAPS-REGISTER.md");
check("dedicated suppression workspace exists", existsSync(resolve(root, "apps/school-admin/src/NotificationSuppressionWorkspace.tsx")));
check("workspace uses shared authenticated session", component.includes("useSchoolAdminSession") && component.includes("request("));
check("workspace is permission gated", component.includes('can("school.settings.manage")'));
check("navigation tab is permission gated", main.includes('id: "emailSuppression"') && main.includes('permission: "school.settings.manage"'));
check("active and released views", component.includes('"ACTIVE"') && component.includes('"RELEASED"'));
check("add and release endpoints wired", component.includes('method: "POST"') && component.includes("/release"));
check("release reason minimum enforced in UI", component.includes("minLength={8}") && component.includes("releaseReason.trim().length < 8"));
check("no email/hash rendered in list", !component.includes("row.emailHash") && !component.includes("row.email"));
check("school-local vs provider-global policy disclosed", component.includes("Provider-global complaint suppression is separate"));
check("API list excludes email hash", routes.includes("select:{id:true,reason:true,status:true,sourceEventId:true,createdAt:true,releasedAt:true,releaseReason:true}"));
check("API list returns school-scoped audit events", routes.includes("notificationEmailSuppressionAudit.findMany") && routes.includes("suppressionId:{in:suppressions.map"));
check("shared request helper handles token refresh", session.includes("refreshSession") && session.includes("response.status === 401"));
check("Arabic shaping limitation remains explicit", (pdf.includes("RTL shaping is not claimed") || read("IMPLEMENTATION-STATUS.md").includes("Arabic glyph coverage is embedded but RTL shaping is not claimed")));
check("P47 gaps appended to master register", register.includes("P47-G001") && register.includes("P47-G007"));
const failed = checks.filter(x => !x.pass);
for (const item of checks) console.log(`${item.pass ? "PASS" : "FAIL"} ${item.name}`);
console.log(`P47 static verifier: ${checks.length - failed.length}/${checks.length} passed`);
if (failed.length) process.exit(1);

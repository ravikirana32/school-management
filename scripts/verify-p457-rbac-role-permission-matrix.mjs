import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = path => readFileSync(resolve(root, path), 'utf8');
const inventory = JSON.parse(read('docs/phases/P457-rbac-role-permission-inventory.json'));
const seed = read('backend/api/prisma/seed.ts');
const pkg = JSON.parse(read('backend/api/package.json'));
const keys = inventory.permissions.map(p=>p.key);
assert.equal(inventory.permissionCount, keys.length, 'permission count matches extracted inventory');
assert.equal(new Set(keys).size, keys.length, 'permission keys are unique');
assert.ok(keys.every(k=>k.includes('.') && !k.startsWith('.') && !k.endsWith('.')), 'permission keys follow module.action form');
assert.ok(inventory.roles.length > 0, 'role inventory is populated');
assert.equal(new Set(inventory.roles.map(r=>r.key)).size, inventory.roles.length, 'role keys are unique');
assert.ok(inventory.roles.filter(r=>Array.isArray(r.permissions)).every(r=>r.permissions.every(p=>keys.includes(p))), 'role permission references resolve');
assert.ok(inventory.roles.every(r=>r.scopeType==='SCHOOL'), 'seeded role scope classification present');
assert.ok(inventory.roles.some(r=>r.key==='SCHOOL_ADMIN' && r.permissions==='ALL_SEEDED_PERMISSIONS'), 'SCHOOL_ADMIN dynamic all-permission grant disclosed');
assert.ok(seed.includes('allSchoolPermissions') && seed.includes('for (const permission of allSchoolPermissions)'), 'SCHOOL_ADMIN grant source exists');
assert.ok(seed.includes('roleRows') && seed.includes('permissionRows'), 'seed role and permission sources exist');
assert.equal(pkg.scripts['verify:p457'], 'node ../../scripts/verify-p457-rbac-role-permission-matrix.mjs', 'verify script registered');
assert.ok(inventory.notes.some(n=>n.includes('static source extraction')), 'static inventory limitation disclosed');
console.log('P457 RBAC Role/Permission Matrix verifier: 11/11 PASS');

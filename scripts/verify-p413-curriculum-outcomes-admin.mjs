import fs from 'node:fs';
import assert from 'node:assert/strict';
const component = fs.readFileSync('apps/school-admin/src/CurriculumOutcomesWorkspace.tsx', 'utf8');
const parent = fs.readFileSync('apps/school-admin/src/OperationalModulesWorkspace.tsx', 'utf8');
const tests = [];
function check(name, condition) { tests.push({ name, pass: Boolean(condition) }); }
check('workspace component exists', fs.existsSync('apps/school-admin/src/CurriculumOutcomesWorkspace.tsx'));
check('uses shared authenticated school session', component.includes('useSchoolAdminSession'));
check('loads curriculum versions and grade levels', component.includes('/versions') && component.includes('/grades'));
check('version selector exists', component.includes('Curriculum version<select'));
check('loads subjects for selected version', component.includes('/subjects'));
check('loads outcomes endpoint', component.includes('/outcomes'));
check('supports review-status filter', component.includes('Review status filter') && component.includes('reviewStatus'));
check('supports grade filter', component.includes('Grade filter') && component.includes('filterGrade'));
check('create outcome form', component.includes('Create curriculum outcome') && component.includes('createOutcome'));
check('validates required outcome code/title/provenance', component.includes('required maxLength={40}') && component.includes('Required provenance note') && component.includes('form.title.trim().length < 3'));
check('includes source reference/edition/url fields', ['sourceReference','sourceEdition','sourceUrl'].every(field => component.includes(field)));
check('includes optional subject association', component.includes('curriculumSubjectId') && component.includes('General / grade-level'));
check('posts create payload to version endpoint', component.includes('"POST", payload') && component.includes('/outcomes'));
check('review action uses PATCH endpoint', component.includes('"PATCH", { reviewStatus }') && component.includes('/review'));
check('review lifecycle respects allowed transitions', component.includes('nextStates') && component.includes('DRAFT: ["IN_REVIEW", "ARCHIVED"]'));
check('actions gated by academics.manage', component.includes('can("academics.manage")') && component.includes('{canManage ?'));
check('read-only state for non-managers', component.includes('read-only access'));
check('outcomes table includes provenance and status', ['Source / provenance','Review','Actions'].every(x => component.includes(x)));
check('empty state for no matching outcomes', component.includes('No outcomes match'));
check('success/error status feedback', component.includes('setMessage(') && component.includes('className="notice"'));
check('embedded into curriculum administration', parent.includes('import { CurriculumOutcomesWorkspace }') && parent.includes('<CurriculumOutcomesWorkspace />'));
check('no board official content falsely claimed', component.includes('No official board content is preloaded'));
const failures = tests.filter(t => !t.pass);
console.log(`P413 Curriculum Outcomes Admin verifier: ${tests.length - failures.length}/${tests.length} PASS`);
for (const t of tests) console.log(`${t.pass ? 'PASS' : 'FAIL'} ${t.name}`);
if (failures.length) process.exit(1);

import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const schema=read("backend/api/prisma/schema.prisma");
const migration=read("backend/api/prisma/migrations/20261117235900_p101_document_data_governance/migration.sql");
const routes=read("backend/api/src/modules/documents/governance.routes.ts");
const app=read("backend/api/src/app.ts");
const parent=read("backend/api/src/modules/parents/parent.routes.ts");
const ui=read("apps/school-admin/src/DataGovernanceWorkspace.tsx");
const main=read("apps/school-admin/src/main.tsx");
const gaps=read("MASTER-OPEN-GAPS-REGISTER.md");
for(const model of ["DataGovernanceRequest","DocumentLegalHold","DocumentRetentionPolicy","DataConsentEvent"])assert.ok(schema.includes(`model ${model} {`),`${model} schema model missing`);
for(const table of ["DataGovernanceRequest","DocumentLegalHold","DocumentRetentionPolicy","DataConsentEvent"])assert.match(migration,new RegExp(`CREATE TABLE "${table}"`),`${table} migration missing`);
assert.equal((migration.match(/ENABLE ROW LEVEL SECURITY/g)||[]).length,4,"all P101 tables must enable RLS");
assert.equal((migration.match(/FORCE ROW LEVEL SECURITY/g)||[]).length,4,"all P101 tables must force RLS");
for(const route of ["/governance/requests","/governance/legal-holds","/governance/retention-policies","/governance/retention-preview","/governance/consent-events"])assert.ok(routes.includes(route),`${route} route missing`);
assert.match(routes,/automaticDeletion:false/,"retention preview must remain non-destructive");
assert.match(app,/governanceRouter/,"governance router not mounted");
assert.match(parent,/dataConsentEvent\.create/,"consent acceptance event missing");
assert.match(parent,/dataConsentEvent\.createMany/,"consent withdrawal events missing");
assert.match(ui,/data governance/i,"School Admin governance UI missing");
assert.match(main,/DataGovernanceWorkspace/,"School Admin tab not mounted");
for(const id of ["P101-G001","P101-G002","P101-G003","P101-G004","P101-G005"])assert.ok(gaps.includes(id),`${id} missing from gap register`);
const a=read("MASTER-OPEN-GAPS-REGISTER.md"),b=read("docs/MASTER-OPEN-GAPS-REGISTER.md");assert.equal(a,b,"root/docs gap registers differ");
console.log("P101 source verifier: PASS (schema/migration/RLS/routes/consent/UI/gap register)");

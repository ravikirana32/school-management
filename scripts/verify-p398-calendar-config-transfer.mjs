for(const c of checks) console.log(`${c.pass?'PASS':'FAIL'} ${c.label}`);
console.log(`RESULT ${checks.filter(c=>c.pass).length}/${checks.length}`);
if(checks.some(c=>!c.pass))process.exitCode=1;

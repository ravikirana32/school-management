check('events array required and capped',/events array with at most 500/.test(transfer));
check('event title required',/title is required/.test(transfer));
check('event type allowlist enforced',/unsupported eventType/.test(transfer)&&/PARENT_MEETING/.test(transfer));
check('start/end timestamps validated',/valid start\/end timestamps/.test(transfer));
check('all-day flag type validated',/isAllDay must be boolean/.test(transfer));
check('instruction-day flag type validated',/isInstructionDay must be boolean/.test(transfer));
check('audience type validated',/audience must be a string/.test(transfer));

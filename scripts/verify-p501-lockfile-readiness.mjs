import fs from 'node:fs';
import assert from 'node:assert/strict';
const checks = [];
const check = (label, condition) => checks.push([label, Boolean(condition)]);
const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
const diagnostic = fs.readFileSync('scripts/p501-lockfile-readiness.mjs', 'utf8');
const bootstrap = fs.readFileSync('scripts/bootstrap-workspace-dependencies.sh', 'utf8');
const rootRegister = fs.readFileSync('MASTER-OPEN-GAPS-REGISTER.md', 'utf8');
const mirrors = ['docs/MASTER-OPEN-GAPS-REGISTER.md', 'docs/phases/MASTER-OPEN-GAPS-REGISTER.md', 'docs/phases/P500/MASTER-OPEN-GAPS-REGISTER.md', 'docs/phases/P501/MASTER-OPEN-GAPS-REGISTER.md'];
check('P501 diagnostic source exists', fs.existsSync('scripts/p501-lockfile-readiness.mjs'));
check('P501 verifier source exists', fs.existsSync('scripts/verify-p501-lockfile-readiness.mjs'));
check('diagnostic parses all workspace package manifests', diagnostic.includes("['apps', 'backend', 'packages']"));
check('diagnostic inventories dependency declarations', diagnostic.includes('dependencyDeclarationCount'));
check('diagnostic counts workspace references', diagnostic.includes('workspaceReferenceCount'));
check('diagnostic validates unresolved workspace references', diagnostic.includes('has no matching package'));
check('diagnostic validates lockfile presence', diagnostic.includes('lockfilePresent'));
check('diagnostic validates exact pnpm version', diagnostic.includes("packageManager === 'pnpm@9.15.0'"));
check('diagnostic validates Node 22 range', diagnostic.includes('nodeMajor >= 22 && nodeMajor < 23'));
check('diagnostic reports registry context', diagnostic.includes('configuredRegistry'));
check('diagnostic readiness requires lockfile and pinned pnpm', diagnostic.includes('lockExists && pnpmAvailable'));
check('bootstrap requires Node and Corepack', bootstrap.includes('command -v node') && bootstrap.includes('command -v corepack'));
check('bootstrap validates pinned manager', bootstrap.includes('EXPECTED="pnpm@9.15.0"'));
check('bootstrap enforces Node 22', bootstrap.includes('Node version must be 22.x'));
check('bootstrap generates lockfile only when missing', bootstrap.includes('pnpm-lock.yaml') && bootstrap.includes('--lockfile-only'));
check('bootstrap performs frozen install', bootstrap.includes('--frozen-lockfile'));
check('bootstrap has bounded network timeout', bootstrap.includes('--config.network-timeout=10000'));
check('bootstrap emits actionable registry failures', bootstrap.includes('Check network/DNS/registry access'));
check('doctor:lockfile script registered', pkg.scripts?.['doctor:lockfile'] === 'node scripts/p501-lockfile-readiness.mjs');
check('verify:p501 script registered', pkg.scripts?.['verify:p501'] === 'node scripts/verify-p501-lockfile-readiness.mjs');
check('P501 gap section recorded', rootRegister.includes('## P501 — Lockfile Readiness'));
check('P501 gaps identify unresolved lockfile generation/install', rootRegister.includes('P501-G002 OPEN') && rootRegister.includes('P501-G003 OPEN'));
check('P501 deliverables checklist exists', fs.existsSync('docs/phases/P501/P501-DELIVERABLES-CHECKLIST.md'));
check('gap register mirrors match root', mirrors.every((file) => fs.existsSync(file) && fs.readFileSync(file, 'utf8') === rootRegister));
for (const [label, pass] of checks) { if (pass) console.log(`PASS ${label}`); else console.log(`FAIL ${label}`); assert.ok(pass, label); }
console.log(`P501 focused assertions: ${checks.length}/${checks.length} PASS`);

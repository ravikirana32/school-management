CREATE TABLE `StudentHealthIncident` (
  `id` VARCHAR(191) NOT NULL,
  `organizationId` VARCHAR(191) NOT NULL,
  `schoolId` VARCHAR(191) NOT NULL,
  `studentId` VARCHAR(191) NOT NULL,
  `caseId` VARCHAR(191) NULL,
  `incidentType` VARCHAR(40) NOT NULL,
  `severity` VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
  `title` VARCHAR(180) NOT NULL,
  `description` TEXT NULL,
  `status` VARCHAR(24) NOT NULL DEFAULT 'OPEN',
  `escalationLevel` INTEGER NOT NULL DEFAULT 0,
  `assignedToUserId` VARCHAR(191) NULL,
  `reportedByUserId` VARCHAR(191) NOT NULL,
  `acknowledgedByUserId` VARCHAR(191) NULL,
  `acknowledgedAt` DATETIME(3) NULL,
  `escalatedAt` DATETIME(3) NULL,
  `resolvedAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `StudentHealthIncident_id_org_school_key` (`id`,`organizationId`,`schoolId`),
  KEY `StudentHealthIncident_org_school_student_status_severity_idx` (`organizationId`,`schoolId`,`studentId`,`status`,`severity`),
  KEY `StudentHealthIncident_org_school_assignee_status_idx` (`organizationId`,`schoolId`,`assignedToUserId`,`status`),
  KEY `StudentHealthIncident_org_school_escalation_status_idx` (`organizationId`,`schoolId`,`escalationLevel`,`status`),
  CONSTRAINT `StudentHealthIncident_student_scope_fk` FOREIGN KEY (`studentId`,`organizationId`,`schoolId`) REFERENCES `Student` (`id`,`organizationId`,`schoolId`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `StudentHealthIncident_case_scope_fk` FOREIGN KEY (`caseId`,`organizationId`,`schoolId`) REFERENCES `StudentHealthCase` (`id`,`organizationId`,`schoolId`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `StudentHealthIncidentNotification` (
  `id` VARCHAR(191) NOT NULL,
  `organizationId` VARCHAR(191) NOT NULL,
  `schoolId` VARCHAR(191) NOT NULL,
  `incidentId` VARCHAR(191) NOT NULL,
  `guardianId` VARCHAR(191) NOT NULL,
  `channel` VARCHAR(20) NOT NULL DEFAULT 'IN_APP',
  `status` VARCHAR(24) NOT NULL DEFAULT 'QUEUED',
  `eventType` VARCHAR(40) NOT NULL DEFAULT 'HEALTH_INCIDENT',
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `StudentHealthIncidentNotification_incident_guardian_event_key` (`incidentId`,`guardianId`,`eventType`),
  KEY `StudentHealthIncidentNotification_org_school_guardian_status_created_idx` (`organizationId`,`schoolId`,`guardianId`,`status`,`createdAt`),
  CONSTRAINT `StudentHealthIncidentNotification_incident_scope_fk` FOREIGN KEY (`incidentId`,`organizationId`,`schoolId`) REFERENCES `StudentHealthIncident` (`id`,`organizationId`,`schoolId`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

-- P542: authorized health case workflow with triage and follow-up history.
CREATE TABLE `StudentHealthCase` (
  `id` VARCHAR(191) NOT NULL,
  `organizationId` VARCHAR(191) NOT NULL,
  `schoolId` VARCHAR(191) NOT NULL,
  `studentId` VARCHAR(191) NOT NULL,
  `caseType` VARCHAR(40) NOT NULL,
  `title` VARCHAR(180) NOT NULL,
  `description` TEXT NULL,
  `priority` VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
  `status` VARCHAR(24) NOT NULL DEFAULT 'OPEN',
  `assignedToUserId` VARCHAR(191) NULL,
  `openedByUserId` VARCHAR(191) NOT NULL,
  `openedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `nextFollowUpAt` DATETIME(3) NULL,
  `closedAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `StudentHealthCase_id_org_school_key` (`id`,`organizationId`,`schoolId`),
  INDEX `StudentHealthCase_org_school_student_status_priority_idx` (`organizationId`,`schoolId`,`studentId`,`status`,`priority`),
  INDEX `StudentHealthCase_org_school_assignee_status_idx` (`organizationId`,`schoolId`,`assignedToUserId`,`status`),
  INDEX `StudentHealthCase_org_school_followup_status_idx` (`organizationId`,`schoolId`,`nextFollowUpAt`,`status`),
  CONSTRAINT `StudentHealthCase_student_scope_fk` FOREIGN KEY (`studentId`,`organizationId`,`schoolId`) REFERENCES `Student` (`id`,`organizationId`,`schoolId`) ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE TABLE `StudentHealthCaseFollowUp` (
  `id` VARCHAR(191) NOT NULL,
  `organizationId` VARCHAR(191) NOT NULL,
  `schoolId` VARCHAR(191) NOT NULL,
  `caseId` VARCHAR(191) NOT NULL,
  `studentId` VARCHAR(191) NOT NULL,
  `recordedByUserId` VARCHAR(191) NOT NULL,
  `note` TEXT NOT NULL,
  `outcome` VARCHAR(1200) NULL,
  `nextFollowUpAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  INDEX `StudentHealthCaseFollowUp_org_school_case_created_idx` (`organizationId`,`schoolId`,`caseId`,`createdAt`),
  CONSTRAINT `StudentHealthCaseFollowUp_case_scope_fk` FOREIGN KEY (`caseId`,`organizationId`,`schoolId`) REFERENCES `StudentHealthCase` (`id`,`organizationId`,`schoolId`) ON DELETE CASCADE ON UPDATE CASCADE
);
